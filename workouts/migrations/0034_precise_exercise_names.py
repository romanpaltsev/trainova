#
# «Жим лёжа» не говорит, штанга это или гантели, — а в справочнике теперь есть и
# то, и другое. Поэтому старые записи ПЕРЕИМЕНОВЫВАЮТСЯ, а не заводятся заново:
# это та же строка БД, значит история, рекорды и графики остаются на месте.
# Добавить «Жим штанги лёжа» рядом значило бы разорвать историю пополам.
#
# Личные упражнения не трогаем вовсе (`owner__isnull=True`): имя, которое человек
# придумал сам, — это его данные. Конфликта с ними и не будет: уникальность
# глобальных имён считается отдельно от личных, поэтому глобальный «Жим штанги
# лёжа» спокойно сосуществует с личным того же имени.
#
# Защитная ветка: если новое имя уже занято ДРУГОЙ глобальной записью (админ мог
# завести её руками), ограничиваемся снарядом — иначе миграция упёрлась бы в
# unique_global_exercise_name и деплой встал бы.
#
# Обратная функция возвращает старые имена и очищает снаряд: до этой миграции
# колонка была пуста у всех — её добавила 0033. Снаряд, проставленный админом
# вручную уже после, откат тоже сотрёт; это цена обратимости.

